/** Курс для демо-данных: суммы были заданы в рублях, приложение показывает сумы */
const UZS_PER_RUB = 150

/** Рубли в сумы, округлённо до десятков тысяч: «76 755 000», а не «76 754 872» */
export const uzs = (rub: number) => Math.round((rub * UZS_PER_RUB) / 10_000) * 10_000

/** Курс доллара по умолчанию, сумов за 1 USD (ЦБ Узбекистана на 07.11.2026); менеджер может поменять в форме */
export const DEFAULT_USD_RATE = 11_987
